/**
 * Chromium keeps one invalidation set for every `:has()` rule in the page.
 * When a rule styles something *below* a `:has()` compound and that target
 * has no class, id, attribute or tag (`… :has(x) .track > *`), the shared set
 * becomes "all descendants might be invalid": any DOM insertion under any
 * element a `:has()` rule watches restyles that element's entire subtree.
 * The sidebar wrapper is one of them and holds the whole window, so every
 * streamed reply update restyled every element and stuttered every running
 * animation. This guard keeps such selectors out of Pine's own styles.
 */
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

const SOURCE_ROOT = path.resolve(__dirname, "..");
/** Generated by shadcn-vue and kept as the CLI writes it. */
const EXCLUDED = [
  `${path.sep}components${path.sep}ui${path.sep}`,
  `${path.sep}styles${path.sep}shadcn-vue.css`,
  `${path.sep}__tests__${path.sep}`,
];

/** The index after the parenthesis group that opens at `open`. */
function closingParen(text: string, open: number): number {
  let depth = 0;
  for (let index = open; index < text.length; index++) {
    if (text[index] === "(") depth++;
    else if (text[index] === ")" && --depth === 0) return index + 1;
  }
  return text.length;
}

/** Drops Vue's `:global(...)` / `:deep(...)` wrappers, keeping what they hold. */
function unwrapVuePseudos(selector: string): string {
  let result = selector;
  for (const name of [":global(", ":deep("]) {
    let start = result.indexOf(name);
    while (start >= 0) {
      const end = closingParen(result, start + name.length - 1);
      const inner = result.slice(start + name.length, end - 1);
      const prefix = name === ":deep(" ? " " : "";
      result = `${result.slice(0, start)}${prefix}${inner}${result.slice(end)}`;
      start = result.indexOf(name);
    }
  }
  return result;
}

/** Splits at `separator` characters that sit outside brackets and parens. */
function splitTopLevel(
  text: string,
  isSeparator: (char: string) => boolean,
): string[] {
  const parts: string[] = [];
  let depth = 0;
  let current = "";
  for (const char of text) {
    if (char === "(" || char === "[") depth++;
    else if (char === ")" || char === "]") depth--;
    if (depth === 0 && isSeparator(char)) {
      parts.push(current);
      current = "";
    } else {
      current += char;
    }
  }
  parts.push(current);
  return parts;
}

/**
 * `:has()` nested in `:nth-child(… of …)` does not feed the shared set, so
 * those groups are left out of the check.
 */
function withoutNthOf(selector: string): string {
  let result = selector;
  let match = /:nth-[a-z-]+\(/.exec(result);
  while (match) {
    const end = closingParen(result, match.index + match[0].length - 1);
    result = `${result.slice(0, match.index)}${result.slice(end)}`;
    match = /:nth-[a-z-]+\(/.exec(result);
  }
  return result;
}

/** Removes pseudo-classes and pseudo-elements, with their arguments. */
function withoutPseudos(compound: string): string {
  let result = compound;
  let match = /::?[a-zA-Z-]+/.exec(result);
  while (match) {
    let end = match.index + match[0].length;
    if (result[end] === "(") end = closingParen(result, end);
    result = `${result.slice(0, match.index)}${result.slice(end)}`;
    match = /::?[a-zA-Z-]+/.exec(result);
  }
  return result.trim();
}

/** True when a complex selector styles a featureless target below `:has()`. */
function hasFeaturelessTargetBelowHas(selector: string): boolean {
  const complex = withoutNthOf(unwrapVuePseudos(selector));
  if (!complex.includes(":has(")) return false;
  const compounds = splitTopLevel(
    complex.replace(/\s*([>+~])\s*/g, " "),
    (char) => /\s/.test(char),
  ).filter(Boolean);
  const last = compounds.length - 1;
  // Only a `:has()` before the target matters; one on the target itself
  // invalidates just that element.
  if (!compounds.slice(0, last).some((compound) => compound.includes(":has(")))
    return false;
  const target = withoutPseudos(compounds[last]);
  return target === "" || target === "*";
}

/** Every style rule's selector list in a stylesheet's text. */
function selectorLists(css: string): string[] {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const preludes: string[] = [];
  let current = "";
  for (const char of text) {
    if (char === "{") {
      const prelude = current.trim();
      if (prelude && !prelude.startsWith("@")) preludes.push(prelude);
      current = "";
    } else if (char === "}" || char === ";") {
      current = "";
    } else {
      current += char;
    }
  }
  return preludes;
}

function styleSources(): { file: string; css: string }[] {
  const files = readdirSync(SOURCE_ROOT, { recursive: true, encoding: "utf8" })
    .map((file) => path.join(SOURCE_ROOT, file))
    .filter((file) => /\.(vue|css)$/.test(file))
    .filter((file) => !EXCLUDED.some((part) => file.includes(part)));
  return files.map((file) => {
    const text = readFileSync(file, "utf8");
    const css = file.endsWith(".vue")
      ? [...text.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)]
          .map((match) => match[1])
          .join("\n")
      : text;
    return { file: path.relative(SOURCE_ROOT, file), css };
  });
}

describe("hasFeaturelessTargetBelowHas", () => {
  it("flags a universal or pseudo-only target below :has()", () => {
    expect(
      hasFeaturelessTargetBelowHas(
        ".slot:is(:hover, :has(:focus-visible)) .track\n  > *",
      ),
    ).toBe(true);
    expect(hasFeaturelessTargetBelowHas(".a:has(.b) > :last-child")).toBe(true);
    expect(
      hasFeaturelessTargetBelowHas(":global(.a:has(.b) .c::before *)"),
    ).toBe(true);
  });

  it("accepts targets with a class, attribute or tag, and :has() subjects", () => {
    expect(hasFeaturelessTargetBelowHas(".slot:has(.b) .track > .kbd")).toBe(
      false,
    );
    expect(hasFeaturelessTargetBelowHas(".a:has(.b) [role='radio']")).toBe(
      false,
    );
    expect(hasFeaturelessTargetBelowHas(".a:has(> input) > input")).toBe(false);
    expect(hasFeaturelessTargetBelowHas(".a > *:has(.b)")).toBe(false);
    expect(hasFeaturelessTargetBelowHas(".a .b > *")).toBe(false);
    expect(
      hasFeaturelessTargetBelowHas(
        ".a > .s:nth-last-child(1 of :not(:has(.c))) > :last-child",
      ),
    ).toBe(false);
  });
});

describe("Pine styles", () => {
  it("never style a featureless target below a :has() compound", () => {
    const offenders: string[] = [];
    for (const { file, css } of styleSources()) {
      for (const list of selectorLists(css)) {
        for (const selector of splitTopLevel(list, (char) => char === ",")) {
          if (hasFeaturelessTargetBelowHas(selector))
            offenders.push(`${file}: ${selector.replace(/\s+/g, " ").trim()}`);
        }
      }
    }
    expect(offenders).toEqual([]);
  });
});
