/** The icon for a name as a model writes it: "map-pin", "MapPin", "map_pin". */
export function iuiIcon(name: unknown): LucideIcon | undefined {
  if (typeof name !== "string") return undefined;
  const key = name
    .trim()
    .replace(/([a-z0-9])([A-Z])/gu, "$1-$2")
    .replace(/[\s_]+/gu, "-")
    .toLowerCase()
    .replace(/-icon$/u, "");
  return ICONS[ALIASES[key] ?? key];
}
