// Magic constants generated by Forge's Vite plugin: where the Vite-bundled
// renderer lives, depending on whether this is a development run.
declare const MAIN_WINDOW_VITE_DEV_SERVER_URL: string;
declare const MAIN_WINDOW_VITE_NAME: string;

/** Where the macOS window buttons sit, aligned with Pine's title bar. */
const TRAFFIC_LIGHT_POSITION = { x: 21, y: 21 };

const SetSidebarVibrancyRequestSchema = z.object({
  enabled: z.boolean(),
});

const SECURE_WEB_PREFERENCES = {
  allowRunningInsecureContent: false,
  contextIsolation: true,
  experimentalFeatures: false,
  nodeIntegration: false,
  sandbox: true,
  scrollBounce: false,
  webSecurity: true,
} as const;

export interface CreateWindowOptions {
  bounds?: Rectangle;
  /** Stays hidden until the quick composer presents it. */
  quickComposerHandoff?: boolean;
}

interface DesktopWindowsOptions {
  iconPath: string;
  /** Replaces showing a ready window, for launch-only smoke tests. */
  smokeTestReady?: () => void;
  record(event: string, details: DiagnosticDetails): void;
  focused(): void;
  destroyed(webContentsId: number): void;
}

/** Built renderer files, which `MAIN_WINDOW_VITE_NAME` names. */
export function rendererRoot(): string {
  return path.join(__dirname, `../renderer/${MAIN_WINDOW_VITE_NAME}`);
}

export function rendererDevUrl(): string | undefined {
  return MAIN_WINDOW_VITE_DEV_SERVER_URL || undefined;
}

/** Window-control glyphs that stay legible on the current Pine theme. */
function titleBarSymbolColor(): string {
  return nativeTheme.shouldUseDarkColors ? "#fafafa" : "#171717";
}

function loadRenderer(window: BrowserWindow, hash?: string): void {
  if (MAIN_WINDOW_VITE_DEV_SERVER_URL) {
    void window.loadURL(
      hash
        ? `${MAIN_WINDOW_VITE_DEV_SERVER_URL}#/${hash}`
        : MAIN_WINDOW_VITE_DEV_SERVER_URL,
    );
  } else {
    void window.loadFile(
      path.join(rendererRoot(), "index.html"),
      hash ? { hash: `/${hash}` } : undefined,
    );
  }
}

/**
 * Pine's windows and the native materials behind them: creation, background
 * colour, sidebar glass and the window-only IPC the renderer sends.
 */
export class DesktopWindows {
  /**
   * The opaque colour each window paints where the page has not drawn yet,
   * e.g. the edge revealed while it resizes. Vibrancy keeps the window
   * transparent; sidebar glass paints the colour natively, behind the glass.
   */
  private readonly backgrounds = new WeakMap<
    BrowserWindow,
    {
      color: string;
      vibrancy: boolean;
      sidebarGlass: boolean;
      /** The visible width of the left sidebar, in CSS pixels. */
      sidebarWidth: number;
    }
  >();

  constructor(private readonly options: DesktopWindowsOptions) {}

  create(options: CreateWindowOptions = {}): BrowserWindow {
    // Matches the theme before the renderer reports its exact colour, so a
    // dark window never opens white.
    const backgroundColor = nativeTheme.shouldUseDarkColors
      ? DARK_WINDOW_BACKGROUND
      : LIGHT_WINDOW_BACKGROUND;
    const mainWindow = new BrowserWindow({
      title: "Pine",
      backgroundColor,
      icon: this.options.iconPath,
      titleBarStyle: "hidden",
      ...(process.platform === "darwin"
        ? { trafficLightPosition: TRAFFIC_LIGHT_POSITION }
        : {
            // Keep the native Windows controls aligned with the custom title
            // bar instead of falling back to the shorter system overlay.
            titleBarOverlay: {
              color: "rgba(0, 0, 0, 0)",
              symbolColor: titleBarSymbolColor(),
              height: 56,
            },
          }),
      // Pine opens straight into the workspace, so the window starts in the
      // resizable project layout.
      width: options.bounds?.width ?? PROJECT_WINDOW_WIDTH,
      height: options.bounds?.height ?? PROJECT_LIST_WINDOW_SIZE.height,
      ...(options.bounds && { x: options.bounds.x, y: options.bounds.y }),
      minWidth: 720,
      minHeight: 540,
      show: false,
      autoHideMenuBar: process.platform !== "darwin",
      webPreferences: {
        ...SECURE_WEB_PREFERENCES,
        preload: path.join(__dirname, "preload.js"),
        ...(options.quickComposerHandoff && {
          additionalArguments: [QUICK_COMPOSER_HANDOFF_ARGUMENT],
        }),
      },
    });
    this.backgrounds.set(mainWindow, {
      color: backgroundColor,
      vibrancy: false,
      sidebarGlass: false,
      sidebarWidth: 0,
    });
    const webContentsId = mainWindow.webContents.id;
    const record = (event: string, details: DiagnosticDetails) =>
      this.options.record(event, details);
    mainWindow.on("unresponsive", () => {
      record("window:unresponsive", { webContentsId });
    });
    mainWindow.on("responsive", () => {
      record("window:responsive", { webContentsId });
    });
    mainWindow.webContents.on("render-process-gone", (_event, details) => {
      record("renderer:gone", {
        webContentsId,
        reason: details.reason,
        exitCode: details.exitCode,
      });
    });
    mainWindow.webContents.on(
      "preload-error",
      (_event, _preloadPath, error) => {
        record("preload:error", { webContentsId, error: error.message });
      },
    );
    installWindowShortcuts(mainWindow.webContents, () => this.create());

    // Focus stops the approval attention request (Windows flashes until the
    // window is focused; macOS bounces until the app activates).
    mainWindow.on("focus", () => this.options.focused());

    mainWindow.once("ready-to-show", () => {
      if (this.options.smokeTestReady) {
        this.options.smokeTestReady();
      } else if (!options.quickComposerHandoff) {
        mainWindow.show();
      }
    });
    mainWindow.webContents.once("destroyed", () => {
      this.options.destroyed(webContentsId);
    });
    mainWindow.webContents.setWindowOpenHandler(() => ({ action: "deny" }));
    mainWindow.webContents.on("will-navigate", (event) => {
      event.preventDefault();
    });

    loadRenderer(mainWindow);
    if (MAIN_WINDOW_VITE_DEV_SERVER_URL && !options.quickComposerHandoff) {
      mainWindow.webContents.openDevTools();
    }
    return mainWindow;
  }

  /**
   * The floating composer: transparent and frameless, above every app and
   * space, with clicks on its empty area passing through to the app behind.
   */
  createQuickComposerPanel(bounds: Rectangle): BrowserWindow {
    const panel = new BrowserWindow({
      ...bounds,
      title: "Pine",
      frame: false,
      transparent: true,
      backgroundColor: TRANSPARENT_WINDOW_BACKGROUND,
      hasShadow: false,
      resizable: false,
      movable: false,
      minimizable: false,
      maximizable: false,
      fullscreenable: false,
      skipTaskbar: true,
      show: false,
      // An NSPanel floats over fullscreen apps without activating Pine's
      // other windows.
      ...(process.platform === "darwin" && { type: "panel" }),
      webPreferences: {
        ...SECURE_WEB_PREFERENCES,
        preload: path.join(__dirname, "preload.js"),
      },
    });
    panel.setAlwaysOnTop(true, "pop-up-menu");
    panel.setVisibleOnAllWorkspaces(true, {
      visibleOnFullScreen: true,
      // Keeps the Dock icon from flickering when the panel is created.
      skipTransformProcessType: true,
    });
    panel.webContents.setWindowOpenHandler(() => ({ action: "deny" }));
    panel.webContents.on("will-navigate", (event) => event.preventDefault());
    loadRenderer(panel, QUICK_COMPOSER_ROUTE_HASH);
    // It plays its own entrance.
    setWindowAnimates(panel, false);
    return panel;
  }

  /**
   * The Liquid Glass card under the floating composer. It loads no page and
   * never takes clicks; the panel above it does.
   */
  createQuickComposerGlass(): BrowserWindow | null {
    if (!isLiquidGlassSupported()) return null;
    const glass = new BrowserWindow({
      width: 1,
      height: 1,
      frame: false,
      transparent: true,
      backgroundColor: TRANSPARENT_WINDOW_BACKGROUND,
      // macOS shapes the shadow from the rounded glass, like a window's, so
      // the composer's edge stands out over any app.
      hasShadow: true,
      resizable: false,
      movable: false,
      minimizable: false,
      maximizable: false,
      fullscreenable: false,
      focusable: false,
      skipTaskbar: true,
      show: false,
      type: "panel",
      webPreferences: { sandbox: true, contextIsolation: true },
    });
    glass.setIgnoreMouseEvents(true);
    glass.setAlwaysOnTop(true, "pop-up-menu");
    glass.setVisibleOnAllWorkspaces(true, {
      visibleOnFullScreen: true,
      skipTransformProcessType: true,
    });
    if (
      !applyLiquidGlass(glass, { cornerRadius: QUICK_COMPOSER_GLASS_RADIUS })
    ) {
      glass.destroy();
      return null;
    }
    setWindowAnimates(glass, false);
    return glass;
  }

  registerIpc(): void {
    ipcMain.handle(CLOSE_WINDOW_CHANNEL, (event): void => {
      BrowserWindow.fromWebContents(event.sender)?.close();
    });

    ipcMain.handle(
      SET_WINDOW_BACKGROUND_CHANNEL,
      (event, color: unknown): void => {
        const window = BrowserWindow.fromWebContents(event.sender);
        const background = window && this.backgrounds.get(window);
        if (!window || !background || !isWindowBackgroundColor(color)) return;
        background.color = color;
        this.applyBackground(window);
      },
    );

    // Pine's own light or dark choice also decides the native materials, so
    // the sidebar glass is dark in a dark Pine on a light system.
    ipcMain.handle(
      SET_THEME_SOURCE_CHANNEL,
      (_event, source: unknown): void => {
        if (!isPineThemeSource(source)) return;
        nativeTheme.themeSource = source;
        for (const window of BrowserWindow.getAllWindows())
          this.applyBackground(window);
      },
    );

    ipcMain.handle(
      SET_WINDOW_LAYOUT_CHANNEL,
      (event, layout: unknown): void => {
        const window = BrowserWindow.fromWebContents(event.sender);
        if (window && isPineWindowLayout(layout))
          applyWindowLayout(window, layout);
      },
    );

    ipcMain.handle(
      PLAN_WINDOW_RESIZE_CHANNEL,
      (event, request: unknown): number => {
        const window = BrowserWindow.fromWebContents(event.sender);
        return window && isPineWindowResizeRequest(request)
          ? planWindowResize(window, request)
          : 0;
      },
    );

    ipcMain.handle(COMMIT_WINDOW_RESIZE_CHANNEL, (event): Promise<void> => {
      const window = BrowserWindow.fromWebContents(event.sender);
      if (!window) return Promise.resolve();
      return commitWindowResize(window, (startedAt) => {
        if (!event.sender.isDestroyed())
          event.sender.send(WINDOW_RESIZE_STARTED_CHANNEL, startedAt);
      });
    });

    ipcMain.on(SET_APP_LOCALE_CHANNEL, (_event, locale: unknown): void =>
      setAppLocale(locale),
    );

    // Sent every frame while the sidebar slides, so the glass keeps up with it.
    ipcMain.on(
      SET_SIDEBAR_GLASS_WIDTH_CHANNEL,
      (event, width: unknown): void => {
        const window = BrowserWindow.fromWebContents(event.sender);
        const background = window && this.backgrounds.get(window);
        if (!window || !background || typeof width !== "number") return;
        if (!Number.isFinite(width)) return;
        background.sidebarWidth = Math.max(0, width);
        if (background.sidebarGlass)
          showSidebarGlass(window, background.sidebarWidth, background.color);
      },
    );

    ipcMain.handle(
      SET_SIDEBAR_VIBRANCY_CHANNEL,
      (event, request: unknown): SetSidebarVibrancyResult => {
        const { enabled } = SetSidebarVibrancyRequestSchema.parse(request);
        if (process.platform !== "darwin") return { applied: false };

        const window = BrowserWindow.fromWebContents(event.sender);
        // Only project windows have a sidebar; the quick composer's own
        // windows share the renderer but must stay clear.
        const background = window && this.backgrounds.get(window);
        if (!window || window.isDestroyed() || !background)
          return { applied: false };

        // Glass like system sidebars where the system has it; Electron's
        // vibrancy before macOS 26.
        const glass =
          enabled &&
          isSidebarGlassSupported() &&
          showSidebarGlass(window, background.sidebarWidth, background.color);
        if (!glass && background.sidebarGlass) hideSidebarGlass(window);
        background.sidebarGlass = glass;
        window.setVibrancy(enabled && !glass ? "sidebar" : null);
        // An opaque window background covers the native material, so it
        // must become fully transparent while the effect is enabled.
        background.vibrancy = enabled;
        this.applyBackground(window);
        this.restoreWindowButtons(window);
        return { applied: true };
      },
    );
  }

  private applyBackground(window: BrowserWindow): void {
    const background = this.backgrounds.get(window);
    if (!background || window.isDestroyed()) return;
    // The overlay's symbols otherwise follow the system theme, not Pine's,
    // and vanish on the opposite background.
    if (process.platform !== "darwin")
      window.setTitleBarOverlay({ symbolColor: titleBarSymbolColor() });
    window.setBackgroundColor(
      background.vibrancy ? TRANSPARENT_WINDOW_BACKGROUND : background.color,
    );
    if (background.sidebarGlass)
      showSidebarGlass(window, background.sidebarWidth, background.color);
  }

  /**
   * Swapping the sidebar material relays out the title bar, and AppKit then
   * puts the window buttons back at their default place; Electron only moves
   * them again when the window next becomes key. Restores them now and once
   * AppKit has finished its own pass.
   */
  private restoreWindowButtons(window: BrowserWindow): void {
    window.setWindowButtonPosition(TRAFFIC_LIGHT_POSITION);
    setTimeout(() => {
      if (!window.isDestroyed())
        window.setWindowButtonPosition(TRAFFIC_LIGHT_POSITION);
    }, 0);
  }
}
